"""The public log (J3, the atlas's TODO-195; JETSAM, The public log and the aggregation tools), run in
`uaun/substrate-jetsam-log`, which vendors this package and calls these functions from its own
`tools/`. Standard library only.

The layout (the log repository's root):

  inbox/<hash>.json                  a packet dropped and not yet ingested (by pull request now, the drop
                                     point at J4); inbox/refused/<hash>.json keeps each refused file
  log/<framework>/<epoch>/<hash>.json  every ingested packet, byte-identical to what was sent; never
                                     edited, never deleted
  log/LEDGER.jsonl                   one line per ingest or refusal, the day and no finer time
  log/TOMBSTONES.jsonl               one line per withdrawal (JT.6, AT.605)
  log/BURN.jsonl                     one line per burned pseudonym-epoch, its reason beside it (JT.12, AT.607)
  enums/<framework>/<release>/enums.yaml   each release's enum file, mirrored (release `dev` included)
  schema/1.0.json                    the packet schema, equal to the vendored package's
  views/                             generated by aggregate, never edited by hand

  ingest(root)     inbox/ to log/, the only write path to log/: the J1 validator against the enum file of
                   the packet's release, then the duplicate, the burn list and the cap (one packet per
                   pseudonym per framework per epoch, JT.12); a refusal keeps the file under inbox/refused/
                   and writes the checks that refused it, never their detail, which could echo content
  aggregate(root)  views/ from log/ and schema/ alone, no network: per framework and release, one view
                   per class, its unit houses (distinct pseudonym-epochs, or packets when the pseudonym is
                   off) per cell with the bucketed counts beside them; a cell with fewer than K houses
                   reads `suppressed (5)` and is named in views/SUPPRESSED.md (JT.13, AT.608); tombstoned
                   and burned packets count in no view; views/REFUSALS.md counts the pipeline's own refusals
  verify(root)     rebuild every view in a temporary folder and diff it with views/; check that every
                   file in log/ is named by its content hash, sits under its framework and epoch, and has
                   exactly one ingested ledger line, and that the logs hold no duplicate; red on anything
  tombstone, burn  append a withdrawal or a burned pseudonym-epoch, each refused when it names nothing
  guard(paths)     the paths a pull request may not change (JT.8, AT.606): log/, views/ and inbox/refused/,
                   which only the automated ingest writes
  correlate(root, atlas)  join each framework's releases to the atlas's alignment ledger, read locally
"""
from __future__ import annotations

import collections
import datetime as dt
import json
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from . import canonical as core
from . import enums as enumfiles
from . import validate as v

K = 5                                   # JT.13 (AT.608)
DEV = "dev"
ROUTES = ("push", "drop", "handoff")    # own push (route 2), the drop point (route 1, J4), the handoff (route 3)
PROTECTED = ("log/", "views/", "inbox/refused/")
COUNTS = ("n", "opened")


def today() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")


def read_jsonl(p: Path) -> list[dict]:
    try:
        return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]
    except OSError:
        return []


def append_jsonl(p: Path, rows: list[dict]) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n")


@dataclass
class Log:
    root: Path

    def __post_init__(self):
        self.root = Path(self.root).resolve()

    inbox = property(lambda s: s.root / "inbox")
    refused_dir = property(lambda s: s.root / "inbox" / "refused")
    logdir = property(lambda s: s.root / "log")
    ledger_path = property(lambda s: s.root / "log" / "LEDGER.jsonl")
    tombstones_path = property(lambda s: s.root / "log" / "TOMBSTONES.jsonl")
    burn_path = property(lambda s: s.root / "log" / "BURN.jsonl")
    views = property(lambda s: s.root / "views")

    def schema(self) -> dict:
        p = self.root / "schema" / "1.0.json"
        return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else v.load_schema()

    def releases(self, framework: str) -> set[str]:
        d = self.root / "enums" / framework
        try:
            return {p.name for p in d.iterdir() if (p / "enums.yaml").is_file()}
        except OSError:
            return set()

    def enums(self, framework: str, release: str):
        p = self.root / "enums" / framework / release / "enums.yaml"
        return enumfiles.load(p) if p.is_file() else None

    def patterns(self) -> list[str]:
        p = self.root / "tools" / "never-store-patterns.json"
        try:
            return json.loads(p.read_text(encoding="utf-8")).get("content") or []
        except (OSError, ValueError):
            return []

    def context(self, framework, release) -> v.Context:
        """The validator's context for one packet: its framework's enum file for its release (a release the
        log holds no enum file for leaves the framework unheld, so the framework or release check refuses),
        the release list (every mirrored release but dev), no attribution digests (a public log publishes
        none; the house's scrubber held the text against them before it was sent) and the never-store
        content patterns."""
        held, rel = {}, {}
        if v.token(framework) and v.token(release):
            rels = self.releases(framework)
            rel[framework] = rels - {DEV}
            # a release the log holds no enum file for: hold another of the framework's files, so the
            # release check (not the framework check) names the gap; a framework with none stays unheld
            pick = release if release in rels else (sorted(rels)[-1] if rels else None)
            e = self.enums(framework, pick) if pick else None
            if e is not None:
                held[framework] = e
        return v.Context(self.schema(), held, rel, set(), self.patterns())

    def ledger(self) -> list[dict]:
        return read_jsonl(self.ledger_path)

    def ingested(self) -> dict[str, dict]:
        return {r["hash"]: r for r in self.ledger() if r.get("state") == "ingested"}

    def tombstoned(self) -> set[str]:
        return {r.get("hash") for r in read_jsonl(self.tombstones_path)}

    def burned(self) -> set[tuple]:
        return {(r.get("framework"), r.get("epoch"), r.get("pseudonym")) for r in read_jsonl(self.burn_path)}

    def packet_path(self, row: dict) -> Path:
        return self.logdir / row["framework"] / row["epoch"] / f"{row['hash']}.json"


# ------------------------------------------------------------------------------ ingest

@dataclass
class Ingest:
    ingested: list[str] = field(default_factory=list)
    refused: list[tuple[str, list[str]]] = field(default_factory=list)


def ingest(root, day: str | None = None, route: str = "push") -> Ingest:
    log, day, out = Log(root), day or today(), Ingest()
    if route not in ROUTES:
        raise ValueError(f"route {route!r} is not one of {', '.join(ROUTES)}")
    try:
        files = sorted(p for p in log.inbox.iterdir() if p.is_file() and p.name != ".gitkeep")
    except OSError:
        return out
    seen = set(log.ingested())
    capped = {(r["framework"], r["epoch"], r["pseudonym"]) for r in log.ingested().values() if r.get("pseudonym")}
    burned = log.burned()
    for p in files:
        raw = p.read_bytes()
        h = core.content_hash(raw)
        try:
            value = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            value = None
        fw = value.get("framework") if isinstance(value, dict) else None
        rel = value.get("release") if isinstance(value, dict) else None
        checks = sorted(v.validate(raw, log.context(fw, rel), name=p.name).checks())
        if not checks:
            key = (fw, value["epoch"], value["pseudonym"])
            if h in seen:
                checks = ["duplicate"]
            elif value["pseudonym"] and key in burned:
                checks = ["burned"]
            elif value["pseudonym"] and key in capped:
                checks = ["cap"]
        if checks:
            log.refused_dir.mkdir(parents=True, exist_ok=True)
            (log.refused_dir / f"{h}.json").write_bytes(raw)
            p.unlink()
            append_jsonl(log.ledger_path, [{"hash": h, "state": "refused", "checks": checks, "day": day}])
            out.refused.append((h, checks))
            continue
        row = {"hash": h, "state": "ingested", "framework": fw, "release": rel, "epoch": value["epoch"],
               "pseudonym": value["pseudonym"], "classes": value["classes"], "route": route, "day": day}
        dest = log.packet_path(row)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(raw)
        p.unlink()
        append_jsonl(log.ledger_path, [row])
        seen.add(h)
        if value["pseudonym"]:
            capped.add((fw, value["epoch"], value["pseudonym"]))
        out.ingested.append(h)
    return out


# ------------------------------------------------------------------------------ the views

def cell_key(e: dict) -> tuple:
    return tuple(sorted((k, json.dumps(x)) for k, x in e.items() if k not in COUNTS and k != "class"))


def render_value(x) -> str:
    return "null" if x is None else (str(x).lower() if isinstance(x, bool) else str(x))


def build_views(log: Log) -> dict[str, str]:
    """Every view's path (relative to views/) and text, from log/ and schema/ alone."""
    schema = log.schema()
    order = list(schema["classes"])
    tomb, burned = log.tombstoned(), log.burned()
    groups: dict[tuple, list[tuple[dict, dict]]] = collections.defaultdict(list)
    excluded = collections.Counter()
    for h, row in sorted(log.ingested().items()):
        if h in tomb:
            excluded["tombstoned"] += 1
            continue
        if row.get("pseudonym") and (row["framework"], row["epoch"], row["pseudonym"]) in burned:
            excluded["burned"] += 1
            continue
        try:
            packet = json.loads(log.packet_path(row).read_bytes().decode("utf-8"))
        except (OSError, ValueError):
            continue        # a ledger line whose file is gone or unreadable: verify names it
        groups[(row["framework"], row["release"])].append((row, packet))

    out, suppressed, index = {}, [], []
    for (fw, rel), items in sorted(groups.items()):
        houses_all = {house(r) for r, _ in items}
        index.append((fw, rel, len(items), len(houses_all)))
        classes = sorted({c for _, pk in items for c in pk["classes"]}, key=order.index)
        for cls in classes:
            fields = [f for f in schema["classes"][cls]["fields"] if f not in COUNTS]
            count_field = next((f for f in COUNTS if f in schema["classes"][cls]["fields"]), None)
            cells: dict[tuple, dict] = {}
            reporting = set()
            for r, pk in items:
                if cls in pk["classes"]:
                    reporting.add(house(r))
                for e in pk["events"]:
                    if e["class"] != cls:
                        continue
                    c = cells.setdefault(cell_key(e), {"event": e, "houses": set(), "counts": collections.Counter()})
                    c["houses"].add(house(r))
                    if count_field:
                        c["counts"][e[count_field]] += 1
            lines = [f"# {fw} {rel}: {cls}", "",
                     f"Generated by tools/aggregate.py from log/ and schema/; never edited by hand. "
                     f"{len(reporting)} house(s) consented to this class in this release; a cell shows only when "
                     f"at least {K} houses fill it (JT.13), and a cell below that reads suppressed ({K}) and is "
                     f"named in views/SUPPRESSED.md.", ""]
            head = fields + ["houses"] + (["counts"] if count_field else [])
            lines += ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
            buckets = schema["lists"]["count0"]
            for key in sorted(cells):
                c = cells[key]
                vals = [render_value(c["event"].get(f)) for f in fields]
                if len(c["houses"]) < K:
                    lines.append("| " + " | ".join(vals + [f"suppressed ({K})"] + ([""] if count_field else [])) + " |")
                    suppressed.append((fw, rel, cls, ", ".join(vals)))
                else:
                    dist = ", ".join(f"{b} ×{c['counts'][b]}" for b in buckets if c["counts"][b])
                    lines.append("| " + " | ".join(vals + [str(len(c["houses"]))] + ([dist] if count_field else [])) + " |")
            if not cells:
                lines.append("| " + " | ".join(["(no event)"] + [""] * (len(head) - 1)) + " |")
            out[f"{fw}/{rel}/{cls}.md"] = "\n".join(lines) + "\n"

    ref = collections.Counter()
    for r in log.ledger():
        if r.get("state") == "refused":
            for c in r.get("checks") or []:
                ref[c] += 1
    lines = ["# The pipeline's own refusals", "",
             "Generated by tools/aggregate.py from log/LEDGER.jsonl, log/TOMBSTONES.jsonl and log/BURN.jsonl. A log "
             "that shows only successes should be distrusted (JETSAM, rule 6).", "",
             "| refused by | packets |", "| --- | --- |"]
    lines += [f"| {c} | {n} |" for c, n in sorted(ref.items())] or ["| (none) | 0 |"]
    lines += ["", "| left out of every view | packets |", "| --- | --- |",
              f"| tombstoned (JT.6) | {excluded['tombstoned']} |", f"| burned (JT.12) | {excluded['burned']} |"]
    out["REFUSALS.md"] = "\n".join(lines) + "\n"
    lines = ["# Suppressed cells", "",
             f"Every cell held under the threshold k = {K} (JT.13), named so its absence is visible; its counts are "
             "not shown here. The packets themselves stay in log/, which is public.", "",
             "| framework | release | class | cell |", "| --- | --- | --- | --- |"]
    lines += [f"| {fw} | {rel} | {cls} | {cell} |" for fw, rel, cls, cell in suppressed] or ["| (none) | | | |"]
    out["SUPPRESSED.md"] = "\n".join(lines) + "\n"
    lines = ["# Views", "", "Generated by tools/aggregate.py. One folder per framework and release.", "",
             "| framework | release | packets | houses |", "| --- | --- | --- | --- |"]
    lines += [f"| {fw} | {rel} | {n} | {hs} |" for fw, rel, n, hs in index] or ["| (none) | | 0 | 0 |"]
    out["INDEX.md"] = "\n".join(lines) + "\n"
    return out


def house(row: dict) -> tuple:
    """The unit a view counts: a pseudonym-epoch, or the packet itself when the pseudonym is off."""
    return ("p", row["pseudonym"], row["epoch"]) if row.get("pseudonym") else ("packet", row["hash"])


def write_views(views: dict[str, str], dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    for rel, text in views.items():
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")


def aggregate(root) -> int:
    log = Log(root)
    views = build_views(log)
    write_views(views, log.views)
    return len(views)


# ------------------------------------------------------------------------------ verify

def verify(root) -> list[str]:
    log, out = Log(root), []
    rows = log.ledger()
    hashes = collections.Counter(r.get("hash") for r in rows if r.get("state") == "ingested")
    out += [f"LEDGER: {h[:12]}... is ingested {n} times" for h, n in hashes.items() if n > 1]
    for r in rows:
        if r.get("state") not in ("ingested", "refused") or not r.get("hash") or not r.get("day"):
            out.append(f"LEDGER: a line lacks its state, hash or day: {json.dumps(r, sort_keys=True)[:80]}")
    ing = log.ingested()
    on_disk = {}
    for p in sorted(log.logdir.rglob("*.json")) if log.logdir.is_dir() else []:
        raw = p.read_bytes()
        h = core.content_hash(raw)
        rel = p.relative_to(log.logdir).as_posix()
        if p.name != f"{h}.json":
            out.append(f"log/{rel}: the name is not the file's content hash")
            continue
        on_disk[h] = rel
        row = ing.get(h)
        if row is None:
            out.append(f"log/{rel}: no ingested ledger line names it")
        elif rel != f"{row['framework']}/{row['epoch']}/{h}.json":
            out.append(f"log/{rel}: not under its framework and epoch")
    out += [f"LEDGER: {h[:12]}... is ingested, and log/ holds no such file" for h in ing if h not in on_disk]
    for t in read_jsonl(log.tombstones_path):
        if t.get("hash") not in ing:
            out.append(f"TOMBSTONES: {str(t.get('hash'))[:12]}... names no ingested packet")
    tcount = collections.Counter(t.get("hash") for t in read_jsonl(log.tombstones_path))
    out += [f"TOMBSTONES: {h[:12]}... is withdrawn {n} times" for h, n in tcount.items() if n > 1]
    bcount = collections.Counter((b.get("framework"), b.get("epoch"), b.get("pseudonym")) for b in read_jsonl(log.burn_path))
    out += [f"BURN: {k[0]} {k[1]} {str(k[2])[:12]}... is burned {n} times" for k, n in bcount.items() if n > 1]
    try:
        if json.loads((log.root / "schema" / "1.0.json").read_text(encoding="utf-8")) != v.load_schema():
            out.append("schema/1.0.json differs from the vendored package's schema")
    except (OSError, ValueError):
        out.append("schema/1.0.json is missing or unreadable")
    with tempfile.TemporaryDirectory() as t:
        fresh = Path(t) / "views"
        write_views(build_views(log), fresh)
        have = {p.relative_to(log.views).as_posix() for p in log.views.rglob("*") if p.is_file()} if log.views.is_dir() else set()
        want = {p.relative_to(fresh).as_posix() for p in fresh.rglob("*") if p.is_file()}
        out += [f"views/{r}: not produced by aggregate" for r in sorted(have - want)]
        out += [f"views/{r}: missing" for r in sorted(want - have)]
        out += [f"views/{r}: differs from what aggregate makes of log/" for r in sorted(have & want)
                if (log.views / r).read_bytes() != (fresh / r).read_bytes()]
    return out


# ------------------------------------------------------------------------------ withdrawal, burning, the guard

def tombstone(root, h: str, by: str, reason: str, day: str | None = None) -> None:
    log = Log(root)
    if by not in ("operator", "burn"):
        raise ValueError("a tombstone is by the operator or by a burn")
    if h not in log.ingested():
        raise ValueError(f"{h[:12]}... names no ingested packet")
    if h in log.tombstoned():
        raise ValueError(f"{h[:12]}... is already withdrawn")
    if not reason.strip():
        raise ValueError("a tombstone carries its reason")
    append_jsonl(log.tombstones_path, [{"hash": h, "day": day or today(), "by": by, "reason": reason}])


def burn(root, framework: str, epoch: str, pseudonym: str, reason: str, day: str | None = None) -> None:
    log = Log(root)
    if not (isinstance(pseudonym, str) and v.HEX64.match(pseudonym)):
        raise ValueError("a burn names a pseudonym, 64 lowercase hex: a packet without one cannot be singled out")
    if (framework, epoch, pseudonym) in log.burned():
        raise ValueError("that pseudonym-epoch is already burned")
    if not reason.strip():
        raise ValueError("a burn carries its reason")
    append_jsonl(log.burn_path, [{"framework": framework, "epoch": epoch, "pseudonym": pseudonym,
                                  "day": day or today(), "reason": reason}])


def guard(paths: list[str]) -> list[str]:
    """The changed paths a pull request may not carry (JT.8): only the automated ingest writes these."""
    return [p for p in paths if any(p == x.rstrip("/") or p.startswith(x) for x in PROTECTED)]


def correlate(root, atlas) -> list[str]:
    """Each framework and release in the views beside the atlas's alignment ledger lines that name it.
    The join is by release only; no field in either ledger names a house."""
    log = Log(root)
    ledger = read_jsonl(Path(atlas) / "alignment" / "ledger.jsonl")
    if not ledger:
        return ["UNREACHABLE: no alignment/ledger.jsonl in the atlas checkout given"]
    out = []
    for fw, rel in sorted({(r["framework"], r["release"]) for r in log.ingested().values()}):
        hits = [r for r in ledger if r.get("framework") == fw and r.get("release") == rel]
        if rel == DEV:
            out.append(f"{fw} {rel}: unreleased builds carry no release, so nothing in the atlas joins to them")
        elif not hits:
            out.append(f"{fw} {rel}: UNMEASURED: the atlas's ledger names no train for this release")
        else:
            out += [f"{fw} {rel}: {r.get('prompt')} {r.get('event')} ({r.get('ts', '')[:10]})" for r in hits]
    return out or ["the log holds no ingested packet"]
